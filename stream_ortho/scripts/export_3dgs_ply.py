"""Export MASt3r-anchored Gaussians to a standard 3DGS PLY (P5.1c Task 8).

Schema (binary little endian, one vertex per Gaussian):

    x, y, z            float32   position, PLANE frame (Z up, same frame as the ortho)
    f_dc_0..2          float32   SH DC coefficients  ((rgb - 0.5) / C0 + residual)
    opacity            float32   logistic activated [0, 1]
    scale_0..2         float32   anisotropic scales (plane units, LOG stored as-is)
    rot_0..3           float32   quaternion, wxyz, PLANE frame
    keyframe_id        int32     source keyframe (debugging / per-frame QA)

`accumulate_keyframes` (scripts/run_p5.py) collects the per-keyframe arrays;
`write_gaussian_ply` only formats and writes them.  Nothing here imports gsplat
or torch, so the unit test runs in the light environment.
"""
from __future__ import annotations

import pathlib
import struct

import numpy as np

_FIELDS = [("x", "f4"), ("y", "f4"), ("z", "f4"),
           ("f_dc_0", "f4"), ("f_dc_1", "f4"), ("f_dc_2", "f4"),
           ("opacity", "f4"),
           ("scale_0", "f4"), ("scale_1", "f4"), ("scale_2", "f4"),
           ("rot_0", "f4"), ("rot_1", "f4"), ("rot_2", "f4"), ("rot_3", "f4"),
           ("keyframe_id", "i4")]

_DTYPE = np.dtype(_FIELDS)


def quat_rotate_batch(q: np.ndarray, R: np.ndarray) -> np.ndarray:
    """Rotate a batch of wxyz quaternions by R: q_p = q_R (*) q_w."""
    w, x, y, z = (q[:, i] for i in range(4))
    # quaternion of R (wxyz)
    tr = R[0, 0] + R[1, 1] + R[2, 2]
    if tr > 0:
        s = np.sqrt(tr + 1.0) * 2
        qw, qx, qy, qz = 0.25 * s, (R[2, 1] - R[1, 2]) / s, (R[0, 2] - R[2, 0]) / s, (R[1, 0] - R[0, 1]) / s
    elif R[0, 0] > R[1, 1] and R[0, 0] > R[2, 2]:
        s = np.sqrt(1.0 + R[0, 0] - R[1, 1] - R[2, 2]) * 2
        qw, qx, qy, qz = (R[2, 1] - R[1, 2]) / s, 0.25 * s, (R[0, 1] + R[1, 0]) / s, (R[0, 2] + R[2, 0]) / s
    elif R[1, 1] > R[2, 2]:
        s = np.sqrt(1.0 + R[1, 1] - R[0, 0] - R[2, 2]) * 2
        qw, qx, qy, qz = (R[0, 2] - R[2, 0]) / s, (R[0, 1] + R[1, 0]) / s, 0.25 * s, (R[1, 2] + R[2, 1]) / s
    else:
        s = np.sqrt(1.0 + R[2, 2] - R[0, 0] - R[1, 1]) * 2
        qw, qx, qy, qz = (R[1, 0] - R[0, 1]) / s, (R[0, 2] + R[2, 0]) / s, (R[1, 2] + R[2, 1]) / s, 0.25 * s

    out = np.empty((len(q), 4), np.float64)
    a = np.stack([w, x, y, z], 1)
    # q_p = q_R (*) q_w  (wxyz Hamilton product)
    out[:, 0] = qw * a[:, 0] - qx * a[:, 1] - qy * a[:, 2] - qz * a[:, 3]
    out[:, 1] = qw * a[:, 1] + qx * a[:, 0] + qy * a[:, 3] - qz * a[:, 2]
    out[:, 2] = qw * a[:, 2] - qx * a[:, 3] + qy * a[:, 0] + qz * a[:, 1]
    out[:, 3] = qw * a[:, 3] + qx * a[:, 2] - qy * a[:, 1] + qz * a[:, 0]
    n = np.linalg.norm(out, axis=1, keepdims=True)
    return out / np.maximum(n, 1e-9)


def write_gaussian_ply(path, means_p, sh_dc, opacity, scales, quats_wxyz,
                       keyframe_id, meta: dict | None = None) -> dict:
    """Write the standard-schema PLY.  Arrays are (N, ·) numpy in PLANE frame.

    Returns {"path", "n", "bytes"}.
    """
    path = pathlib.Path(path)
    n = int(len(means_p))
    for name, arr in (("means", means_p), ("sh_dc", sh_dc), ("opacity", opacity),
                      ("scales", scales), ("quats", quats_wxyz)):
        arr = np.asarray(arr)
        assert arr.shape[0] == n, f"{name}: {arr.shape} vs N={n}"
        assert np.isfinite(arr).all(), f"{name}: non-finite values"
    kf = np.asarray(keyframe_id, np.int32).reshape(n)

    data = np.zeros(n, dtype=_DTYPE)
    data["x"], data["y"], data["z"] = (np.asarray(means_p, np.float32)[:, i] for i in range(3))
    sh = np.asarray(sh_dc, np.float32)
    data["f_dc_0"], data["f_dc_1"], data["f_dc_2"] = sh[:, 0], sh[:, 1], sh[:, 2]
    data["opacity"] = np.asarray(opacity, np.float32).reshape(-1)
    sc = np.asarray(scales, np.float32)
    data["scale_0"], data["scale_1"], data["scale_2"] = sc[:, 0], sc[:, 1], sc[:, 2]
    qt = np.asarray(quats_wxyz, np.float32)
    data["rot_0"], data["rot_1"], data["rot_2"], data["rot_3"] = (qt[:, i] for i in range(4))
    data["keyframe_id"] = kf

    meta = meta or {}
    header = ["ply", "format binary_little_endian 1.0",
              "comment Generated by stream-ortho P5 pipeline (MASt3r-anchored 3DGS)"]
    for k, v in meta.items():
        header.append(f"comment {k}: {v}")
    header.append(f"element vertex {n}")
    for name, fmt in _FIELDS:
        header.append(f"property {'float' if fmt == 'f4' else 'int'} {name}")
    header.append("end_header")

    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "wb") as f:
        f.write(("\n".join(header) + "\n").encode("ascii"))
        data.tofile(f)
    return {"path": str(path), "n": n, "bytes": path.stat().st_size}


def read_gaussian_ply(path) -> dict:
    """Minimal reader for tests/viewer parity: header + binary fields."""
    path = pathlib.Path(path)
    with open(path, "rb") as f:
        header = []
        while True:
            line = f.readline().decode("ascii").strip()
            header.append(line)
            if line == "end_header":
                break
        n = int(next(l for l in header if l.startswith("element vertex")).split()[-1])
        props = [l.split()[-1] for l in header if l.startswith("property ")]
        raw = f.read(_DTYPE.itemsize * n)
    data = np.frombuffer(raw, dtype=_DTYPE, count=n)
    return {"header": header, "props": props, "data": data, "n": n}
